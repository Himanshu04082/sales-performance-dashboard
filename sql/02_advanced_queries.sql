USE superstore;


-- A1. DENSE_RANK — Rank sub-categories by profit
-- Ties receive the same rank without gaps.
SELECT
    p.sub_category,
    ROUND(SUM(f.profit), 2) AS total_profit,
    DENSE_RANK() OVER (
        ORDER BY SUM(f.profit) DESC
    ) AS profit_dense_rank
FROM fact_orders f
JOIN dim_products p
    ON f.product_id = p.product_id
GROUP BY p.sub_category
ORDER BY profit_dense_rank;


-- A2. LEAD — Compare each month's revenue with the following month
WITH monthly AS (
    SELECT
        order_year,
        order_month,
        SUM(sales) AS monthly_sales
    FROM fact_orders
    GROUP BY order_year, order_month
)
SELECT
    order_year,
    order_month,
    ROUND(monthly_sales, 2) AS monthly_sales,
    ROUND(
        LEAD(monthly_sales) OVER (
            ORDER BY order_year, order_month
        ), 2
    ) AS next_month_sales,
    ROUND(
        LEAD(monthly_sales) OVER (
            ORDER BY order_year, order_month
        ) - monthly_sales,
        2
    ) AS change_to_next_month
FROM monthly
ORDER BY order_year, order_month;


-- A3. 3-Month Moving Average of Revenue
WITH monthly AS (
    SELECT
        order_year,
        order_month,
        SUM(sales) AS monthly_sales
    FROM fact_orders
    GROUP BY order_year, order_month
)
SELECT
    order_year,
    order_month,
    ROUND(monthly_sales, 2) AS monthly_sales,
    ROUND(
        AVG(monthly_sales) OVER (
            ORDER BY order_year, order_month
            ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
        ),
        2
    ) AS moving_avg_3mo
FROM monthly
ORDER BY order_year, order_month;


-- A4. Rolling 3-Month Revenue Total
WITH monthly AS (
    SELECT
        order_year,
        order_month,
        SUM(sales) AS monthly_sales
    FROM fact_orders
    GROUP BY order_year, order_month
)
SELECT
